function getRuntimeOrigin(explicitOrigin?: string): string {
  if (explicitOrigin) return explicitOrigin.replace(/\/$/, '');
  if (typeof window !== 'undefined' && window.location?.origin) {
    return window.location.origin.replace(/\/$/, '');
  }
  return 'https://accounticca.ai.studio';
}

function normalizeWhitespace(input: string): string {
  return String(input || '').replace(/\s+/g, ' ').trim();
}

/**
 * Strips markdown, HTML/JSX tags, URLs, tables, and bilingual "--- বাংলা" splits
 * into clean, natural English prose suitable for meta descriptions and OG cards.
 */
export function stripMarkdownAndHtml(raw: string): string {
  if (!raw) return '';
  // Prefer primary English lead section before Bangla divider
  const englishOnly = raw.split(/(?:\n|^)---\s*\n\s*(?:#+\s*)?(?:বাংলা|in bangla)/i)[0] || raw;

  return normalizeWhitespace(
    englishOnly
      // Remove fenced code blocks
      .replace(/```[\s\S]*?```/g, ' ')
      // Remove custom/HTML tags
      .replace(/<[^>]+>/g, ' ')
      // Remove markdown images
      .replace(/!\[[^\]]*\]\([^)]+\)/g, ' ')
      // Convert markdown links [label](url) -> label
      .replace(/\[([^\]]+)\]\([^)]+\)/g, '$1')
      // Remove markdown table divider & pipe heavy lines
      .replace(/^\|.*\|$/gm, ' ')
      // Remove heading markers & blockquote markers & list bullets
      .replace(/^[#>*\-+]+\s+/gm, ' ')
      .replace(/^\d+\.\s+/gm, ' ')
      // Remove inline emphasis / backticks
      .replace(/[*_`~]/g, '')
  );
}

/**
 * Extracts high-value statutory references & legal entities mentioned in content
 * to enrich auto-generated keywords and search relevance.
 */
export function extractKeyStatutes(text: string): string[] {
  if (!text) return [];
  const patterns: Array<[RegExp, string]> = [
    [/Income Tax Act,?\s*2023/i, 'Income Tax Act 2023'],
    [/Finance (?:Act|Ordinance),?\s*202[4-7]/i, 'Finance Act 2026'],
    [/VAT (?:&|and)?\s*SD Act,?\s*2012|Value Added Tax/i, 'VAT & SD Act 2012'],
    [/Companies Act,?\s*1994/i, 'Companies Act 1994'],
    [/Bangladesh Labour Act,?\s*2006|Labour Act 2006/i, 'Bangladesh Labour Act 2006'],
    [/Stamp Act,?\s*1899/i, 'Stamp Act 1899'],
    [/Registration Act,?\s*1908/i, 'Registration Act 1908'],
    [/Sixth Schedule|6th Schedule/i, 'Sixth Schedule'],
    [/Mushak\s*\d+(?:\.\d+)?/gi, 'Mushak Forms'],
    [/\bRJSC\b/, 'RJSC Bangladesh'],
    [/\bNBR\b|National Board of Revenue/i, 'NBR Bangladesh'],
    [/\bTDS\b|Tax Deducted at Source/i, 'TDS Bangladesh'],
    [/\bVDS\b|VAT Deduction at Source/i, 'VDS Bangladesh'],
    [/\bBIDA\b/, 'BIDA Bangladesh'],
    [/\bICAB\b|\bDVC\b/, 'ICAB DVC'],
  ];

  const found = new Set<string>();
  for (const [regex, label] of patterns) {
    if (regex.test(text)) {
      found.add(label);
    }
  }

  // Extract explicit Section/SRO citations (up to 4)
  const sectionMatches = text.match(/\b(?:Section|Sec\.?)\s+\d+(?:\([0-9A-Za-z]+\))?/gi) || [];
  for (const sec of sectionMatches.slice(0, 3)) {
    found.add(normalizeWhitespace(sec.replace(/^Sec\.?/i, 'Section')));
  }

  const sroMatches = text.match(/\bSRO\s*(?:No\.?\s*)?\d+(?:-[A-Za-z]+\/\d+)?/gi) || [];
  for (const sro of sroMatches.slice(0, 2)) {
    found.add(normalizeWhitespace(sro));
  }

  return Array.from(found);
}

/**
 * Extracts up to 3 top H2 headings from markdown article content for OG highlights.
 */
function extractContentHighlights(markdownContent: string, fallbackItems: string[]): string[] {
  const englishOnly = (markdownContent || '').split(/(?:\n|^)---\s*\n\s*(?:#+\s*)?(?:বাংলা|in bangla)/i)[0] || '';
  const headings: string[] = [];
  const lines = englishOnly.split('\n');
  for (const line of lines) {
    const m = line.match(/^##\s+(.+)$/);
    if (m && m[1]) {
      const cleaned = normalizeWhitespace(m[1].replace(/[*_`[\]()]/g, '').replace(/^\d+\.\s*/, ''));
      if (cleaned.length >= 8 && cleaned.length <= 90 && !/^(overview|introduction|conclusion|summary|disclaimer)$/i.test(cleaned)) {
        headings.push(cleaned);
      }
    }
    if (headings.length >= 3) break;
  }
  return headings.length > 0 ? headings : fallbackItems.slice(0, 3);
}

/**
 * Trims text cleanly at a natural word boundary without splitting words.
 */
function trimAtWordBoundary(text: string, maxLength: number, addEllipsis = true): string {
  const clean = normalizeWhitespace(text);
  if (clean.length <= maxLength) return clean;
  const limit = addEllipsis ? maxLength - 3 : maxLength;
  const slice = clean.slice(0, Math.max(10, limit));
  const lastSpace = slice.lastIndexOf(' ');
  const cut = lastSpace > limit * 0.55 ? slice.slice(0, lastSpace) : slice;
  const trimmed = cut
    .replace(/(?:\s+(?:&|and|or|for|of|in|to|with|by|under|on|from|the|a|an))+$/i, '')
    .replace(/[,:;\-–—&\s]+$/, '');
  return addEllipsis ? `${trimmed}...` : trimmed;
}

/**
 * Optimizes `<title>` to hit the SEO sweet spot (30–60 chars) while preserving
 * core focus keywords and brand recognition.
 */
export function buildOptimizedTitle(rawTitle: string, fallbackContext?: string): string {
  let clean = normalizeWhitespace(rawTitle)
    .replace(/\s*\|\s*(?:E-?Lawyers|Accounticca|Compliance Hub).*$/i, '')
    .replace(/\s*[–—-]\s*(?:E-?Lawyers|Accounticca).*$/i, '')
    .trim();

  if (!clean) clean = 'Legal & Tax Compliance Guide';

  // If short enough to append short brand cleanly within 60 chars
  const withBrand = `${clean} | ${SHORT_BRAND}`;
  if (withBrand.length >= 30 && withBrand.length <= 60) {
    return withBrand;
  }
  if (clean.length >= 30 && clean.length <= 60) {
    return clean;
  }
  if (clean.length < 30) {
    const enriched = fallbackContext
      ? `${clean} (${fallbackContext}) | ${SHORT_BRAND}`
      : `${clean} – Bangladesh Guide | ${SHORT_BRAND}`;
    return enriched.length <= 60 ? enriched : trimAtWordBoundary(enriched, 60, false);
  }

  // Title > 60 chars: prefer keeping core part before parenthetical or subtitle if still >= 35 chars
  const beforeParen = clean.replace(/\s*\([^)]{10,}\)\s*$/, '').trim();
  if (beforeParen.length >= 35 && beforeParen.length <= 60) {
    const parenWithBrand = `${beforeParen} | ${SHORT_BRAND}`;
    return parenWithBrand.length <= 60 ? parenWithBrand : beforeParen;
  }

  const colonIdx = clean.indexOf(':');
  if (colonIdx >= 30 && colonIdx <= 58) {
    const beforeColon = clean.slice(0, colonIdx).trim();
    const colonWithBrand = `${beforeColon} | ${SHORT_BRAND}`;
    return colonWithBrand.length <= 60 ? colonWithBrand : beforeColon;
  }

  return trimAtWordBoundary(clean, 60, false);
}

/**
 * Builds a search-engine optimal meta description (strictly 120–160 characters)
 * from explicit summary, excerpt, and cleaned prose with a clear compliance CTA.
 */
export function buildOptimizedMetaDescription(
  primaryText: string,
  secondaryProse: string,
  ctaSuffix: string
): string {
  const cleanPrimary = stripMarkdownAndHtml(primaryText);
  const cleanSecondary = stripMarkdownAndHtml(secondaryProse);
  let candidate = cleanPrimary || cleanSecondary || ctaSuffix;

  if (candidate.length < 120 && cleanSecondary && !cleanPrimary.includes(cleanSecondary.slice(0, 30))) {
    const firstSentence = cleanSecondary.split(/(?<=[.!?])\s+/)[0] || cleanSecondary;
    if (firstSentence && firstSentence.length > 25) {
      candidate = `${candidate.replace(/[.!?]+$/, '')}. ${firstSentence}`;
    }
  }

  if (candidate.length < 120) {
    candidate = `${candidate.replace(/[.!?]+$/, '')}. ${ctaSuffix}`;
  }

  if (candidate.length <= 160) {
    return candidate;
  }

  // Prefer complete first sentence if within 120-160 chars
  const sentences = candidate.split(/(?<=[.!?])\s+/);
  if (sentences[0] && sentences[0].length >= 120 && sentences[0].length <= 160) {
    return sentences[0];
  }

  // Combine sentence 1 + truncated sentence 2 cleanly to land near 155 chars
  return trimAtWordBoundary(candidate, 158, true);
}

/**
 * Builds a slightly richer Open Graph social card summary (target 120–195 chars)
 * tailored for LinkedIn, Facebook, Slack, Discord, and WhatsApp previews.
 */
export function buildOpenGraphSummaryText(
  primaryText: string,
  secondaryProse: string,
  contextTag?: string
): string {
  const cleanPrimary = stripMarkdownAndHtml(primaryText);
  const cleanSecondary = stripMarkdownAndHtml(secondaryProse);
  let summary = cleanPrimary || cleanSecondary;

  if (summary.length < 110 && cleanSecondary) {
    const extra = cleanSecondary.split(/(?<=[.!?])\s+/).slice(0, 2).join(' ');
    if (extra && !summary.includes(extra.slice(0, 25))) {
      summary = `${summary.replace(/[.!?]+$/, '')}. ${extra}`;
    }
  }

  if (contextTag && summary.length + contextTag.length + 3 <= 195 && !summary.toLowerCase().includes(contextTag.toLowerCase())) {
    summary = `${summary.replace(/[.!?]+$/, '')} — ${contextTag}.`;
  }

  return summary.length <= 195 ? summary : trimAtWordBoundary(summary, 195, true);
}

function normalizeSeoPath(pathOrUrl: string): string {
  if (!pathOrUrl) return '/';
  if (pathOrUrl.startsWith('http://') || pathOrUrl.startsWith('https://')) {
    try {
      return new URL(pathOrUrl).pathname || '/';
    } catch {
      return '/';
    }
  }
  const withoutHash = pathOrUrl.split('#')[0];
  const withoutQuery = withoutHash.split('?')[0];
  const prefixed = withoutQuery.startsWith('/') ? withoutQuery : `/${withoutQuery}`;
  return prefixed === '/' ? '/' : prefixed.replace(/\/$/, '');
}

function estimateWordCount(content: string): number {
  const clean = stripMarkdownAndHtml(content);
  if (!clean) return 0;
  return clean.split(/\s+/).filter(Boolean).length;
}

function buildMetaTagsArray(meta: {
  title: string;
  description: string;
  keywords: string[];
  robots: string;
  author?: string;
  openGraph: OpenGraphSummary;
  twitter: TwitterCardSummary;
}): MetaTagDescriptor[] {
  const tags: MetaTagDescriptor[] = [
    { attribute: 'name', key: 'title', content: meta.title },
    { attribute: 'name', key: 'description', content: meta.description },
  ];

  if (meta.keywords.length > 0) {
    tags.push({ attribute: 'name', key: 'keywords', content: meta.keywords.join(', ') });
  }
  if (meta.author) {
    tags.push({ attribute: 'name', key: 'author', content: meta.author });
  }
  tags.push({ attribute: 'name', key: 'robots', content: meta.robots });

  // Open Graph core tags
  tags.push(
    { attribute: 'property', key: 'og:type', content: meta.openGraph.type },
    { attribute: 'property', key: 'og:url', content: meta.openGraph.url },
    { attribute: 'property', key: 'og:title', content: meta.openGraph.title },
    { attribute: 'property', key: 'og:description', content: meta.openGraph.description },
    { attribute: 'property', key: 'og:site_name', content: meta.openGraph.siteName },
    { attribute: 'property', key: 'og:locale', content: meta.openGraph.locale },
    { attribute: 'property', key: 'og:image', content: meta.openGraph.image.url },
    { attribute: 'property', key: 'og:image:alt', content: meta.openGraph.image.alt },
    { attribute: 'property', key: 'og:image:width', content: String(meta.openGraph.image.width) },
    { attribute: 'property', key: 'og:image:height', content: String(meta.openGraph.image.height) }
  );

  // Open Graph article-specific tags
  if (meta.openGraph.type === 'article' && meta.openGraph.articleMeta) {
    const am = meta.openGraph.articleMeta;
    if (am.publishedTime) {
      tags.push({ attribute: 'property', key: 'article:published_time', content: am.publishedTime });
    }
    if (am.modifiedTime) {
      tags.push({ attribute: 'property', key: 'article:modified_time', content: am.modifiedTime });
    }
    if (am.author) {
      tags.push({ attribute: 'property', key: 'article:author', content: am.author });
    }
    if (am.section) {
      tags.push({ attribute: 'property', key: 'article:section', content: am.section });
    }
    if (am.tags) {
      for (const tag of am.tags.slice(0, 8)) {
        tags.push({ attribute: 'property', key: 'article:tag', content: tag });
      }
    }
  }

  // Twitter Card tags
  tags.push(
    { attribute: 'name', key: 'twitter:card', content: meta.twitter.card },
    { attribute: 'name', key: 'twitter:url', content: meta.openGraph.url },
    { attribute: 'name', key: 'twitter:title', content: meta.twitter.title },
    { attribute: 'name', key: 'twitter:description', content: meta.twitter.description },
    { attribute: 'name', key: 'twitter:image', content: meta.twitter.image },
    { attribute: 'name', key: 'twitter:image:alt', content: meta.twitter.imageAlt },
    { attribute: 'name', key: 'twitter:site', content: meta.twitter.site },
    { attribute: 'name', key: 'twitter:creator', content: meta.twitter.creator }
  );

  return tags;
}

function escapeHtmlAttr(value: string): string {
  return String(value || '')
    .replace(/&/g, '&amp;')
    .replace(/"/g, '&quot;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;');
}

export function buildMetaTagsHtml(meta: Pick<GeneratedPageSeoMetadata, 'title' | 'canonicalUrl' | 'metaTags' | 'structuredData'>): string {
  const lines: string[] = [
    `<title>${escapeHtmlAttr(meta.title)}</title>`,
    `<link rel="canonical" href="${escapeHtmlAttr(meta.canonicalUrl)}" />`,
  ];

  for (const tag of meta.metaTags) {
    lines.push(
      `<meta ${tag.attribute}="${escapeHtmlAttr(tag.key)}" content="${escapeHtmlAttr(tag.content)}" />`
    );
  }

  for (const schema of meta.structuredData) {
    lines.push(`<script type="application/ld+json">${JSON.stringify(schema)}</script>`);
  }

  return lines.join('\n');
}

