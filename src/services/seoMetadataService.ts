function findMatchingCatalogTool(input: ToolMetadataInput): CatalogToolSeed | undefined {
  const pathCandidate = input.canonicalPath || input.canonicalUrl;
  const normalizedInputPath = pathCandidate ? normalizeSeoPath(pathCandidate) : undefined;

  if (input.toolId) {
    const cleanId = input.toolId.toLowerCase();
    const standaloneMatch = STANDALONE_TOOL_CATALOG.find(
      (t) => t.id.toLowerCase() === cleanId || t.id.toLowerCase().replace(/-tool$/, '') === cleanId.replace(/-tool$/, '')
    );
    if (standaloneMatch) return standaloneMatch;

    const searchableMatch = searchableTaxTools.find(
      (t) => t.id.toLowerCase() === cleanId || t.id.toLowerCase().replace(/-tool$/, '') === cleanId.replace(/-tool$/, '')
    );
    if (searchableMatch) {
      return {
        id: searchableMatch.id,
        name: searchableMatch.name,
        shortName: searchableMatch.shortName,
        category: searchableMatch.category,
        description: searchableMatch.description,
        path: searchableMatch.path,
        badge: searchableMatch.badge,
        tags: searchableMatch.tags,
      };
    }
  }

  if (normalizedInputPath) {
    const byPathStandalone = STANDALONE_TOOL_CATALOG.find(
      (t) => normalizeSeoPath(t.path) === normalizedInputPath
    );
    if (byPathStandalone) return byPathStandalone;

    const byPathSearchable = searchableTaxTools.find(
      (t) => normalizeSeoPath(t.path) === normalizedInputPath
    );
    if (byPathSearchable) {
      return {
        id: byPathSearchable.id,
        name: byPathSearchable.name,
        shortName: byPathSearchable.shortName,
        category: byPathSearchable.category,
        description: byPathSearchable.description,
        path: byPathSearchable.path,
        badge: byPathSearchable.badge,
        tags: byPathSearchable.tags,
      };
    }
  }

  return undefined;
}

